function escText(s) {
  return String(s)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/\n/g, '<br>')
}

function escAttr(s) {
  return String(s).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;')
}

function placeTour() {
  if (!ui.tour) return
  const step = ui.tour.queue[ui.tour.i]
  const el = step && tourTarget(step.sel)
  const hole = document.getElementById('tour-hole')
  const card = document.getElementById('tour-card')
  if (!el || !hole || !card) return
  const r = el.getBoundingClientRect()
  const pad = 8
  hole.style.top = Math.max(0, r.top - pad) + 'px'
  hole.style.left = Math.max(0, r.left - pad) + 'px'
  hole.style.width = r.width + pad * 2 + 'px'
  hole.style.height = r.height + pad * 2 + 'px'
  const cw = 360
  const ch = card.offsetHeight || 180
  const gap = 12
  let left = Math.min(Math.max(16, r.left), window.innerWidth - cw - 16)
  let top = r.bottom + gap
  const overflowBottom = top + ch > window.innerHeight - 16
  if (overflowBottom && r.top - ch - gap >= 16) top = r.top - ch - gap
  if (top < 16) top = 16
  card.style.top = top + 'px'
  card.style.left = left + 'px'
}
