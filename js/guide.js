function tourTarget(sel) {
  return sel
    .split(',')
    .map((s) => s.trim())
    .map((s) => document.querySelector(s))
    .find(Boolean)
}

function tourQueue(key) {
  const g = guideOf(key)
  return defaultTourSteps(g).filter((s) => tourTarget(s.sel))
}

function startTour() {
  const key = ui.pageGuide
  const queue = tourQueue(key)
  if (!queue.length) return
  ui.tour = { key, i: 0, queue }
  ui.ask = null
}

function startAsk() {
  const key = ui.pageGuide
  const g = guideOf(key)
  ui.ask = {
    key,
    input: '',
    messages: [
      {
        role: 'assistant',
        text: `Я в контексте «${g.title}». ${g.lead} Спросите про этот экран — или нажмите готовый вопрос.`,
      },
    ],
  }
  ui.tour = null
}

function answerGuide(key, q) {
  const g = guideOf(key)
  const t = String(q || '')
    .toLowerCase()
    .replace(/ё/g, 'е')
  const hit = (g.faqs || []).find((f) => f.k.some((k) => t.includes(k)))
  if (hit) return hit.a
  if (!t.trim() || /что это|зачем|за что|можно сделать|этот экран|этот раздел|для чего/.test(t)) {
    return g.lead
  }
  return `${g.lead}\n\nЕсли вопрос про другой раздел — откройте его: ассистент привязан к текущей странице.`
}

function pushAsk(text) {
  const q = String(text || '').trim()
  if (!q || !ui.ask) return
  ui.ask.messages.push({ role: 'user', text: q })
  ui.ask.messages.push({ role: 'assistant', text: answerGuide(ui.ask.key, q) })
  ui.ask.input = ''
}

