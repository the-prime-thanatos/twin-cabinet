/* js/screens-landing.js — MVP presentation: Project is the new entity. */
function landEl(title, why) {
  return `<li><span class="land-el-t">${title}</span><span class="land-el-d">${why}</span></li>`
}

function landSec(s) {
  const cta = s.href
    ? `<button class="btn" type="button" data-nav="${s.href}">Открыть экран</button>`
    : ''
  const more = (s.more || [])
    .map((h) => `<button class="btn btn-ghost" type="button" data-nav="${h.href}">${h.label}</button>`)
    .join('')
  return `<article class="land-sec" id="${s.id}">
    <header class="land-sec-head">
      <div class="land-sec-title">
        <div class="land-kicker">${s.icon ? icon(s.icon, 16) : ''}${s.kicker}</div>
        <h2 class="h2">${s.title}</h2>
      </div>
      <div class="land-sec-cta">${cta}${more}</div>
    </header>
    ${s.lead ? `<p class="land-lead">${s.lead}</p>` : ''}
    <div class="land-cols">
      <div>
        <div class="land-col-h">Почему собрано так</div>
        <p>${s.built}</p>
      </div>
      <div>
        <div class="land-col-h">Элементы — зачем они здесь</div>
        <ul class="land-els">${s.els.map((e) => landEl(e[0], e[1])).join('')}</ul>
      </div>
      <div>
        <div class="land-col-h">Что получает человек</div>
        <p>${s.gets}</p>
      </div>
    </div>
    ${s.sample ? `<div class="land-sample">${s.sample()}</div>` : ''}
  </article>`
}

